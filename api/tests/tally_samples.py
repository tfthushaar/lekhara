def envelope(body: str) -> str:
    return (
        '<?xml version="1.0" encoding="UTF-16"?>\n<ENVELOPE>\n'
        " <HEADER><TALLYREQUEST>Import Data</TALLYREQUEST></HEADER>\n"
        " <BODY><IMPORTDATA><REQUESTDESC><REPORTNAME>All Masters</REPORTNAME>\n"
        "  <STATICVARIABLES><SVCURRENTCOMPANY>Kaveri Homes LLP</SVCURRENTCOMPANY></STATICVARIABLES>\n"
        " </REQUESTDESC><REQUESTDATA>" + body + "</REQUESTDATA></IMPORTDATA></BODY>\n</ENVELOPE>\n"
    )


def full_xml_utf16() -> bytes:
    """Masters and vouchers in one file, saved the way Tally saves Unicode XML."""
    return b"\xff\xfe" + envelope(MASTERS + VOUCHERS).encode("utf-16-le")


def vouchers_only_xml() -> bytes:
    return envelope(VOUCHERS).encode("utf-8")


def masters_only_xml() -> bytes:
    return envelope(MASTERS).encode("utf-8")


